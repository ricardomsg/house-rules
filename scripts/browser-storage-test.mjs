import assert from 'node:assert/strict';
import { importTypeScript } from './load-typescript.mjs';
const { browserStorage, joinRequestKey } = await importTypeScript('lib/browser-storage.ts');
const store = () => { const data = new Map(); return { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key) }; };
const blocked = { getItem() { throw Error('blocked'); }, setItem() { throw Error('quota'); }, removeItem() { throw Error('blocked'); } };
globalThis.window = { localStorage: blocked, sessionStorage: store() };
assert.equal(browserStorage.setItem('seat', 'credential'), true);
assert.equal(window.sessionStorage.getItem('seat'), 'credential');
window.localStorage = { ...store(), getItem: () => 'stale local value', setItem() { throw Error('quota'); } };
window.sessionStorage.setItem('read-new-seat', 'new session value');
assert.equal(browserStorage.getItem('read-new-seat'), 'new session value');
window.localStorage = blocked; window.sessionStorage = blocked;
assert.equal(browserStorage.setItem('memory-seat', 'kept'), false);
assert.equal(browserStorage.getItem('memory-seat'), 'kept');
const request = joinRequestKey('ROOM', ' Guest ');
assert.equal(joinRequestKey('ROOM', 'Guest'), request);
assert.notEqual(joinRequestKey('ROOM', 'Another guest'), request);
assert.doesNotThrow(() => browserStorage.removeItem('memory-seat'));
assert.equal(browserStorage.getItem('memory-seat'), null);
delete globalThis.window;
assert.equal(browserStorage.getItem('seat'), null);
console.log('PASS: restricted/quota storage keeps the active seat, prefers the saved session over stale local data, and retries with the same request key.');
